pub(super) unsafe fn install(base:usize) {
    // Startup only, before any game callback can execute. Engine publishes original before patch.
    REFUSE.store(base+0x651464,Ordering::Release);
    let mut original=std::ptr::null_mut();
    skyline::hooks::A64HookFunction((base+0x6510f4) as *const _,
        mii_ordinary_gate_entry as *const _, &mut original);
    assert!(!original.is_null(),"ordinary Player gate trampoline unavailable");
    CONTINUE.store(original as usize,Ordering::Release);
}
/// U5, W-M2-4 (`refactor/wp5c/R68-GATE-WRITER.md`; WP-R CATALOG §R68): at `0x6510f4` an O whose `+0x4c`
/// bit0 is set skips configure (`0x651334–0x65137c`), so its record index `+0x68` and tokens
/// `+0x6c..0x7c` keep whatever an earlier request left, and the native bind `0x651444 → 0x67e7d0`
/// then retires the record that stale index names (index 0 = Player0's pair, M-R1 (b)). For a tracked
/// Mii payload this writes the words configure writes for the staged descriptor
/// (`identity_view::configured_mii_words`) before any native read of them for this request. Returns
/// the words written, or `None`: bit0 clear (configure runs natively), no exact-Mii staging, or the O
/// span fails validation (the existing refusal path then decides). WP-E row
/// `mii_ordinary_gate::install_r68_on_skip`: every scope, `RestoresNative`, deliberately not gated
/// (a refusal would bring the stale index back).
unsafe fn install_r68_on_skip(o:usize,descriptor:&[u8;0x70])
    ->Option<crate::engine::swap::identity_view::ConfiguredMiiWords> {
    if !super::native::span(o,0xb0,true) {return None;}
    if crate::engine::seams::native_fields::load_acquire_u32(o+0x4c)&1==0 {return None;}
    let words=crate::engine::swap::identity_view::configured_mii_words(descriptor)?;
    std::ptr::write_volatile((o+0x68) as *mut u16,words.index);
    for (i,token) in words.tokens.iter().enumerate() {std::ptr::write_volatile((o+0x6c+i*4) as *mut u32,*token);}
    crate::engine::compat::logging::diagnostic(format_args!("[Gate] r68 installed O={:#x} index={} tokens={:x?} skip=true",
        o,words.index,words.tokens));
    Some(words)
}
/// U5 call order: a tracked Mii payload gets the configure-equivalent words before `prequeue`, so the
/// publication proof sees them with its receipt; the same-class retained-O arm instead keeps the O
/// untouched for its own proof (it requires the old tokens in `O+0x6c..`, `SameClass::prepare_write`)
/// and gets them only when that proof refused and the request continues natively.
unsafe fn r68_before_prequeue(payload:Option<([u8;0x70],bool)>,selected:usize)
    ->Option<crate::engine::swap::identity_view::ConfiguredMiiWords> {
    match payload {
        Some((descriptor,false))=>install_r68_on_skip(selected,&descriptor),
        _=>None,
    }
}
unsafe fn r68_on_continuation(payload:Option<([u8;0x70],bool)>,selected:usize) {
    if let Some((descriptor,true))=payload {install_r68_on_skip(selected,&descriptor);}
}
#[no_mangle]
unsafe extern "C" fn mii_ordinary_gate_decide(entry:usize,selected:usize,native_sp:usize)->usize {
    crate::runtime::threads::headroom("mii_ordinary_gate_decide");
    // stream/stack: each arm is its own frame (inline(never)), so the callback's stack holds only the arm that runs.
    if super::super::mii_ordinary_cpu::tracked(entry) {return decide_cpu(entry,selected,native_sp);}
    if super::super::mii_managed_helper::tracked(entry) {return decide_helper(entry,selected,native_sp);}
    decide_player(entry,selected,native_sp)
}
#[inline(never)]
unsafe fn decide_cpu(entry:usize,selected:usize,native_sp:usize)->usize {
    {
        let valid_stack=native_sp.is_multiple_of(16) && super::native::span(native_sp,0xf0,false);
        let payload=if valid_stack {super::super::mii_ordinary_cpu::mii_payload_descriptor(entry)} else {None};
        let installed=r68_before_prequeue(payload,selected);
        return if valid_stack && super::super::mii_ordinary_cpu::prequeue(entry,selected,installed) {
            CONTINUE.load(Ordering::Acquire)
        } else if valid_stack && super::super::mii_ordinary_cpu::continue_natively(entry) {
            // D-PTA1b: states 1-3 already destroyed the window; for a plain-kind track the native
            // state-6 tail installs the staged descriptor and the loader settles (release in service).
            r68_on_continuation(payload,selected);
            CONTINUE.load(Ordering::Acquire)
        } else {
            super::super::mii_ordinary_cpu::refuse(entry,"prequeue refused; native epilogue selected");
            REFUSE.load(Ordering::Acquire)
        };
    }
}
#[inline(never)]
unsafe fn decide_helper(entry:usize,selected:usize,native_sp:usize)->usize {
    {
        let valid_stack=native_sp.is_multiple_of(16) && super::native::span(native_sp,0xf0,false);
        return if valid_stack && super::super::mii_managed_helper::prequeue(entry,selected) {
            CONTINUE.load(Ordering::Acquire)
        } else {
            super::super::mii_managed_helper::refuse(entry,"prequeue refused; native epilogue selected");
            REFUSE.load(Ordering::Acquire)
        };
    }
}
#[inline(never)]
unsafe fn decide_player(entry:usize,selected:usize,native_sp:usize)->usize {
    if !super::tracked(entry) {return CONTINUE.load(Ordering::Acquire);}
    let valid_stack=native_sp.is_multiple_of(16) && super::native::span(native_sp,0xf0,false);
    let payload=if valid_stack {super::mii_payload_descriptor(entry)} else {None};
    // The Player proof refuses an initialised O before any index/token compare: no receipt to pass.
    r68_before_prequeue(payload,selected);
    if valid_stack && super::prequeue(entry,selected) {
        CONTINUE.load(Ordering::Acquire)
    } else if valid_stack && super::continue_natively(entry) {
        // Row 7 / D-PTA1b: states 1-3 already destroyed the window; the native state-6 tail installs
        // the staged descriptor and the loader settles (release in service).
        r68_on_continuation(payload,selected);
        CONTINUE.load(Ordering::Acquire)
    } else {
        super::refuse(entry,"prequeue refused; native epilogue selected");
        REFUSE.load(Ordering::Acquire)
    }
}
