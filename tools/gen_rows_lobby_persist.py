def sections(elf):
    shoff, = struct.unpack_from("<Q", elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    headers = [struct.unpack_from("<IIQQQQ", elf, shoff + i * shentsize) for i in range(shnum)]
    strtab = headers[shstrndx][4]
    out = {}
    for name, _t, _f, addr, off, size in headers:
        end = elf.index(b"\0", strtab + name)
        out[elf[strtab + name:end].decode()] = (addr, off, size)
    return out


def main():
    elf = open(sys.argv[1], "rb").read()
    addr, off, size = sections(elf)[".text"]
    lines = [
        "//! rc.6 lobby settings persist seam rows, generated by `tools/gen_rows_lobby_persist.py` from the owned 13.0.5 main",
        f"//! ELF (sha256 {hashlib.sha256(elf).hexdigest()}); regenerate rather than hand-edit.",
        "use super::*;",
        "",
        "pub const ROWS: &[Seam] = &[",
    ]
    for label, at, kind, note in ROWS:
        assert addr <= at and at + 64 <= addr + size, hex(at)
        window = elf[off + at - addr: off + at - addr + 64]
        guard = ", ".join(f"0x{b:02x}" for b in window)
        lines += [
            f'    Seam {{ label: "{label}", group: "{GROUP}", offset: {at:#x},',
            f"           kind: {kind},",
            f"           guard: [{guard}],",
            '           feature: "", scopes: Scopes::LOBBY_WAITING, read_only: false, per_frame: false,',
            "           sharing: Sharing::None,",
            f'           note: "{note}" }},',
        ]
    lines.append("];")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")
    print("wrote", sys.argv[2], len(ROWS), "rows")


if __name__ == "__main__":
    main()
