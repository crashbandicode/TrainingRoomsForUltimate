import json,re,sys
S=sys.argv[1]
cat=json.load(open(S+'/scripts/stage-grid/catalog.json'))
src=open(S+'/training_mod_consts/src/character_items.rs').read()
m=re.search(r'ITEM_NAMES: \[&str; 38\] = \[(.*?)\];',src,re.S)
items=re.findall(r'"((?:[^"\\]|\\.)*)"',m.group(1))
print(len(cat),len(items))
def esc(s): return s.replace('\\','\\\\').replace('"','\\"')
out=['//! The names the item and stage grids show: the stage list (the earlier fork\'s `scripts/stage-grid/catalog.json`, ours-new, names only: no picture)','//! and the 38 give-item names (the fork\'s `training_mod_consts/src/character_items.rs`, ours-new). Generated by `tools/gen_catalog.py`; carried data, see CARRY-OVER.md.','','pub static STAGES: [&str; %d] = ['%len(cat)]
for c in cat: out.append('    "%s",'%esc(c['name']))
out.append('];'); out.append('')
out.append('pub static ITEMS: [&str; %d] = ['%len(items))
for i in items: out.append('    "%s",'%esc(i))
out.append('];'); out.append('')
open(sys.argv[2],'w').write('\n'.join(out))