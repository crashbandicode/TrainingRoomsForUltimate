#!/usr/bin/env python3
"""Package 6 carry-over inventory.

Reads docs/provenance/provenance-files.json and feature-groups.json (stage m5i), and for every
ours-new file of the package-6 feature groups hashes the same path in a newer frozen stage
(default m5o). Only ours-new paths are opened (hashing); no mixed or upstream file is read.
Writes docs/provenance/pkg6-inventory.json and prints a summary.
"""
import hashlib, json, os, sys, collections

STAGES = "/home/intpa/smash-training-lobby/artifacts/enhancements/console-practice91/lobby-parity167/parked-reuse175/refactor/stages"
PKG6 = [
    "Hot-swap engine",
    "Mii fighters",
    "Cycle preload",
    "CPU-as-P1 handoff",
    "Kirby hats",
    "Practice stages",
    "Lobby practice",
    "Character items",
    "Seam guards",
    "Diagnostics, probes",
    "Input display renderer optimisation",
    "Fork release/size docs",
]

# Files that exist in a newer stage but not in the m5i scan. A path absent from the scan is not an upstream file
# (the scan lists every upstream path), so these are fork-new. Assigned to a feature by hand.
EXTRA = {
    "training_mod_consts/src/notice_queue.rs": "Cycle preload",
    "training_mod_consts/src/body_bank/mii_publish.rs": "Hot-swap engine",
    "src/log_stress.rs": "Diagnostics, probes",
    "training_mod_consts/src/log_stress.rs": "Diagnostics, probes",
    "docs/skyline-logger-race.md": "Diagnostics, probes",
    "docs/cpu-rolls-apply.md": "Fork release/size docs",
}
# Not carried by package 6: the fork's CPU-rolls apply patch is package 2's SPEC-cpu-02 section 5 (clean-room).
NOT_CARRIED = {"src/training/cpu_rolls.rs", "training_mod_consts/src/cpu_rolls.rs"}


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def lines(path):
    try:
        with open(path, "rb") as f:
            data = f.read()
        if b"\0" in data[:4096]:
            return None
        return data.count(b"\n") + (0 if data.endswith(b"\n") or not data else 1)
    except OSError:
        return None

def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    stage_name = sys.argv[2] if len(sys.argv) > 2 else "m5o"
    stage = os.path.join(STAGES, stage_name, "stage")
    files = {f["path"]: f for f in json.load(open(os.path.join(root, "docs/provenance/provenance-files.json")))["files"]}
    groups = json.load(open(os.path.join(root, "docs/provenance/feature-groups.json")))
    out = {"stage": stage_name, "features": {}, "new_in_stage_not_in_scan": []}
    known = set(files)
    for gname, g in groups.items():
        if not any(gname.startswith(p) for p in PKG6):
            continue
        rows = []
        for p in g["files"]:
            meta = files[p]
            if meta["origin"] != "ours-new":
                raise SystemExit("not ours-new: " + p)
            full = os.path.join(stage, p)
            if not os.path.exists(full):
                rows.append({"path": p, "missing_in_stage": True})
                continue
            s = sha(full)
            rows.append({
                "path": p,
                "bytes": os.path.getsize(full),
                "lines": lines(full),
                "sha256": s,
                "m5i_sha16": meta["stage_sha256"],
                "changed_since_m5i": not s.startswith(meta["stage_sha256"]),
            })
        out["features"][gname] = rows
    for p, feat in EXTRA.items():
        full = os.path.join(stage, p)
        if not os.path.exists(full):
            continue
        key = next(k for k in out["features"] if k.startswith(feat))
        out["features"][key].append({"path": p, "bytes": os.path.getsize(full), "lines": lines(full), "sha256": sha(full),
                                      "m5i_sha16": None, "changed_since_m5i": True, "added_after_m5i": True})
    # paths present in the newer stage but not in the m5i scan (so not upstream either)
    for dp, dn, fn in os.walk(stage):
        dn[:] = [d for d in dn if d not in ("target", ".git")]
        for n in fn:
            rel = os.path.relpath(os.path.join(dp, n), stage)
            if rel not in known:
                out["new_in_stage_not_in_scan"].append(rel)
    out["new_in_stage_not_in_scan"].sort()
    out["not_carried"] = sorted(NOT_CARRIED)
    json.dump(out, open(os.path.join(root, "docs/provenance/pkg6-inventory.json"), "w"), indent=1)

    with open(os.path.join(root, "docs/provenance/pkg6-inventory.md"), "w") as f:
        f.write(f"# Package 6 carry inventory (stage {stage_name})\n\n")
        f.write("Generated by `tools/pkg6_inventory.py`; every row is an `ours-new` file (origin per `provenance-files.json`). ")
        f.write("`sha256` is the file in the stage named above; `chg` marks a file whose content differs from stage m5i (the scan's stage) ")
        f.write("and `new` a file that does not exist in m5i.\n")
        for g, rows in out["features"].items():
            f.write(f"\n## {g}\n\n| path | lines | bytes | sha256 | chg |\n| --- | ---: | ---: | --- | --- |\n")
            for r in sorted(rows, key=lambda r: r["path"]):
                mark = "new" if r.get("added_after_m5i") else ("chg" if r.get("changed_since_m5i") else "")
                f.write(f"| `{r['path']}` | {r.get('lines') if r.get('lines') is not None else ''} | {r['bytes']} | `{r['sha256']}` | {mark} |\n")
        f.write("\n## Not carried by package 6\n\n")
        for p in out["not_carried"]:
            f.write(f"- `{p}`\n")
    tot = collections.Counter()
    for g, rows in out["features"].items():
        n = len(rows); b = sum(r.get("bytes", 0) for r in rows); l = sum(r.get("lines") or 0 for r in rows)
        ch = sum(1 for r in rows if r.get("changed_since_m5i")); ms = sum(1 for r in rows if r.get("missing_in_stage"))
        print(f"{g[:60]:60} files={n:4} bytes={b:9} lines={l:6} changed_since_m5i={ch} missing={ms}")
    print("new in", stage_name, "not in scan:", len(out["new_in_stage_not_in_scan"]))

main()