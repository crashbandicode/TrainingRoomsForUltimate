"""Write src/model/aim_f13_fixture.rs: Pikachu's 14 first-pass casts of F13 trace boot `f13-trace-0a17-1`.

Usage: gen_aim_f13_fixture.py <f13-trace/flight/retake-1/ms-pikachu> <audit/osf_eval_f13.json> <out.rs>

Each row is one game frame as the plugin sampled it: the frame's offset from the press, the status, airborne, facing,
the position and the left stick the game read. The expected parts come from the research check of the outcome rule
(`osf_eval.py`): `parts` with rule D, `all` without it (which equals the travel table of `e7667f26`).
"""
import json
import os
import sys

src, expected, out = sys.argv[1:4]
want = {r['cast']: r for r in json.load(open(expected)) if r['folder'] == 'ms-pikachu'}
lines = [
    '//! Generated by tools/gen_aim_f13_fixture.py from F13 trace boot `f13-trace-0a17-1`: Pikachu\'s 14 first-pass casts.',
    '//! One row a game frame: offset from the press, status, airborne, facing, position, left stick. Do not edit.',
    '',
    'pub struct Row { pub rel: i16, pub status: i32, pub air: bool, pub lr: i8, pub x: f32, pub y: f32, pub lx: i8, pub ly: i8 }',
    '/// `parts`: (part, direction bin) with rule D; `all`: without it, which is the travel table\'s answer at `e7667f26`.',
    'pub struct Cast { pub name: &\'static str, pub rows: &\'static [Row], pub parts: &\'static [(u8, u8)], pub all: &\'static [(u8, u8)] }',
    '',
]
casts = []
for name in sorted(want):
    rows = []
    with open(os.path.join(src, f'frames-{name}.tsv')) as f:
        head = f.readline().rstrip('\n').split('\t')
        for line in f:
            row = dict(zip(head, line.rstrip('\n').split('\t')))
            if not row['status']:
                continue   # three casts have no status on their first row, four frames before the press
            rows.append('    Row {{ rel: {}, status: {}, air: {}, lr: {}, x: {:.4}, y: {:.4}, lx: {}, ly: {} }},'.format(
                int(row['rel']), row['status'].split()[0], 'true' if row['situation'] == '2' else 'false',
                int(row['lr']), float(row['x']), float(row['y']), int(row['lx']), int(row['ly'])))
    ident = 'ROWS_' + ''.join(c if c.isalnum() else '_' for c in name).upper()
    lines += [f'const {ident}: [Row; {len(rows)}] = ['] + rows + ['];']
    pairs = lambda key: ', '.join(f'({n}, {b})' for n, b in want[name][key])
    casts.append(f'    Cast {{ name: "{name}", rows: &{ident}, parts: &[{pairs("osf")}], all: &[{pairs("osf_keep_default")}] }},')
lines += ['', f'pub const CASTS: [Cast; {len(casts)}] = ['] + casts + ['];', '']
open(out, 'w').write('\n'.join(lines))
print(f'{len(casts)} casts, {sum(1 for l in lines if l.startswith("    Row {"))} rows -> {out}')
