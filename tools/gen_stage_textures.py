import json
src = '/home/intpa/smash-training-lobby/artifacts/enhancements/console-practice91/lobby-parity167/parked-reuse175/refactor/stages/m5q/stage/scripts/stage-grid/catalog.json'
d = json.load(open(src))
out = []
out.append('//! The stage thumbnails\' UI texture files (SPEC-core-07 section 4.5): per selectable stage, the name that completes')
out.append('//! `ui/replace/stage/stage_1/stage_1_<name>.bntx` (`ui/replace_patch/...` for a patch stage). Data only, no pixels.')
out.append('//! Carried from the fork\'s `scripts/stage-grid/catalog.json` (stage m5q, ours-new; `name_id` lower-cased as the game')
out.append('//! files are named); generated by `tools/gen_stage_textures.py`, not edited by hand.')
out.append('')
out.append('/// `(stage id, file name part, patch stage)`; the stage ids are those of `engine::stages::lobby_stages::STAGES`.')
out.append('pub const STAGE_TEXTURES: &[(u32, &str, bool)] = &[')
for e in d:
    out.append('    (%d, "%s", %s),' % (e['stage_id'], e['name_id'].lower(), 'true' if e['is_patch'] else 'false'))
out.append('];')
out.append('')
out.append('/// The texture file of a stage id, if the stage has one (the Waiting Room has none).')
out.append('pub fn texture_of(stage_id: u32) -> Option<(&\'static str, bool)> {')
out.append('    STAGE_TEXTURES.iter().find(|(id, _, _)| *id == stage_id).map(|(_, name, patch)| (*name, *patch))')
out.append('}')
out.append('')
out.append('/// The archive-relative path of a stage\'s thumbnail, written into `out` (no allocation); its length.')
out.append('pub fn path_into(stage_id: u32, out: &mut [u8; 96]) -> Option<usize> {')
out.append('    let (name, patch) = texture_of(stage_id)?;')
out.append('    let prefix: &[u8] = if patch { b"ui/replace_patch/stage/stage_1/stage_1_" } else { b"ui/replace/stage/stage_1/stage_1_" };')
out.append('    let suffix: &[u8] = b".bntx";')
out.append('    let total = prefix.len() + name.len() + suffix.len();')
out.append('    if total > out.len() {')
out.append('        return None;')
out.append('    }')
out.append('    out[..prefix.len()].copy_from_slice(prefix);')
out.append('    out[prefix.len()..prefix.len() + name.len()].copy_from_slice(name.as_bytes());')
out.append('    out[prefix.len() + name.len()..total].copy_from_slice(suffix);')
out.append('    Some(total)')
out.append('}')
out.append('')
out.append('#[cfg(test)]')
out.append('mod tests {')
out.append('    use super::*;')
out.append('')
out.append('    fn path(id: u32) -> String {')
out.append('        let mut buffer = [0u8; 96];')
out.append('        let len = path_into(id, &mut buffer).unwrap();')
out.append('        String::from_utf8(buffer[..len].to_vec()).unwrap()')
out.append('    }')
out.append('')
out.append('    #[test]')
out.append('    fn paths_follow_the_documented_examples() {')
out.append('        assert_eq!(path(0), "ui/replace/stage/stage_1/stage_1_battlefield.bntx");')
out.append('        assert_eq!(path(3), "ui/replace/stage/stage_1/stage_1_end.bntx");')
out.append('        assert_eq!(path(347), "ui/replace_patch/stage/stage_1/stage_1_battlefields.bntx");')
out.append('        assert!(texture_of(311).is_none(), "the Waiting Room has no picture");')
out.append('    }')
out.append('')
out.append('    #[test]')
out.append('    fn the_table_has_115_unique_stages_of_which_12_are_patch_stages() {')
out.append('        assert_eq!(STAGE_TEXTURES.len(), 115);')
out.append('        for (i, (id, name, _)) in STAGE_TEXTURES.iter().enumerate() {')
out.append('            assert!(STAGE_TEXTURES[..i].iter().all(|(other, n, _)| other != id && n != name), "{id} {name}");')
out.append('        }')
out.append('        assert_eq!(STAGE_TEXTURES.iter().filter(|(_, _, patch)| *patch).count(), 12);')
out.append('    }')
out.append('}')
open('/home/intpa/smash-training-lobby/TrainingRoomsForUltimate-pkg5/src/model/ui/stage_textures.rs', 'w').write('\n'.join(out) + '\n')
print(len(d), sum(1 for e in d if e['is_patch']))
