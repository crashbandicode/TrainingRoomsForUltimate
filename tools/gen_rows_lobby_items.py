#!/usr/bin/env python3
"""Write `src/model/seams/native_seams/rows_lobby_items.rs` (Phase 2 N11, Lobby Items) from the owned 13.0.5 main ELF.

    python3 -I tools/gen_rows_lobby_items.py <main-13.0.5.elf> <out.rs>

The rows below are the source of truth for labels, kinds and notes; the guard bytes come from the ELF, and the host test
`native_seams::tests::compared_rows_match_the_owned_elf` re-checks them on every `cargo test`.
"""
import hashlib
import struct
import sys

GROUP = "lobby_items"
ROWS = [
    ("lobby_items.spawn_switch", 0x15D9A80, "SeamKind::Hook { form: HookForm::Inline, placement: Placement::Mid }",
     "Mid-function inline hook on `cbz w8, 0x15da59c`, the item spawner's test of its control's switch byte (`ldrb w8,[c,#0x30]` "
     "at 0x15d9a7c; zero takes the update straight to its epilogue, the native off path). In a qualified waiting scene with Lobby "
     "Items Off the callback sets x8 = 0; elsewhere it leaves the context alone. 8-byte aligned: a far form replaces "
     "0x15d9a80..0x15d9a8c (cbz w8, ldr x8,[x22,#0x550], ldrb w9,[x8,#8], cbz w9; both cbz relocated). No direct branch in .text "
     "targets 0x15d9a84..0x15d9a8c, the function 0x15d99b0..0x15da5c0 has no x16/x17 operand, NZCV is dead here (next reader "
     "b.lt 0x15d9aa0 after subs). Card scan 2026-11-03: no plugin refers to it."),
    ("lobby_items.switch_load", 0x15D9A60, "SeamKind::Relied",
     "The update's manager-state check (`ldr x8,[x19]; ldr w8,[x8,#0xc]; cmp w8,#1`) and the control load the hook relies on: "
     "x19 = ItemManager, c = [[x19+0xa0]], `ldrb w8,[c,#0x30]` just before the hooked cbz."),
    ("lobby_items.spawner_thunk", 0x1358680, "SeamKind::Relied",
     "`adrp x8; ldr x0,[x8,#0x70]; cbz x0; b 0x15d99b0`: the per-frame update table's entry (.rodata 0x3c89390) calls the spawner "
     "with the ItemManager singleton main+0x52c4070, the manager the removal step reads."),
]


def sections(elf):
    shoff, = struct.unpack_from("<Q", elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    headers = [struct.unpack_from("<IIQQQQ", elf, shoff + i * shentsize) for i in range(shnum)]
    strtab = headers[shstrndx][4]
    out = {}
    for name, _t, _f, addr, off, size in headers:
        end = elf.index(b"\0", strtab + name)
        out[elf[strtab + name:end].decode()] = (addr, off, size)
    return out


def main():
    elf = open(sys.argv[1], "rb").read()
    addr, off, size = sections(elf)[".text"]
    lines = [
        f"//! Phase 2 N11 (Lobby Items) seam rows, generated by `tools/gen_rows_lobby_items.py` from the owned 13.0.5 main ELF",
        f"//! (sha256 {hashlib.sha256(elf).hexdigest()}); regenerate rather than hand-edit.",
        "use super::*;",
        "",
        "pub const ROWS: &[Seam] = &[",
    ]
    for label, at, kind, note in ROWS:
        assert addr <= at and at + 64 <= addr + size, hex(at)
        window = elf[off + at - addr: off + at - addr + 64]
        guard = ", ".join(f"0x{b:02x}" for b in window)
        lines += [
            f'    Seam {{ label: "{label}", group: "{GROUP}", offset: {at:#x},',
            f"           kind: {kind},",
            f"           guard: [{guard}],",
            '           feature: "practice-stage", scopes: Scopes::ALL, read_only: false, per_frame: true,',
            "           sharing: Sharing::None,",
            f'           note: "{note}" }},',
        ]
    lines.append("];")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")
    print("wrote", sys.argv[2], len(ROWS), "rows")


if __name__ == "__main__":
    main()
