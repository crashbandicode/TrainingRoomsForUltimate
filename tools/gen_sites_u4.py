#!/usr/bin/env python3
"""Write `src/model/sites_u4.rs` from the owned 13.0.5 main ELF.

    python3 -I tools/gen_sites_u4.py <elf> <out.rs>

The table below is the source of truth for names, kinds and notes (stream u4: the run-time texture helper,
`src/runtime/ui/texture.rs`); the guard bytes come from the ELF. `tests/u4_sites.rs` re-checks every row
against the same ELF on each `cargo test`.
"""
import struct
import sys

ROWS = [
    ("ui_tex_find_handle", 0x353DA30, "Called",
     "The game's file-resource lookup `(u32* out_handle, u64 hash40)`: writes the resource handle of a file path hash (0xffffff when the "
     "file is not in the resource table) and takes one reference on it. The same call the game's UI asset loader makes for a stage or "
     "fighter UI texture, so a mod's replacement file is what loads. Its words 10 and 11 (`adrp x9, 0x5332000; ldr x20, [x9, #0xf20]`) name the "
     "file-resource service's global slot (`main+0x5332f20`), which the plugin decodes from them (`UI_TEX_SERVICE_SLOT_WORDS_OFFSET`)."),
    ("ui_tex_make", 0x37852A0, "Called",
     "The game's UI texture constructor `(shared_ptr_out[2], const u32* handle)`: allocates the 0x68-byte UI texture, takes its own reference on "
     "the handle and queues the file for loading. Writes the shared pointer (a 0x10-byte holder whose +8 is the UI texture, and its "
     "control block) to the first argument."),
    ("ui_tex_poll", 0x37A3510, "Called",
     "The game's UI texture update `(ui_texture*)`: once the file is loaded it copies the BNTX, builds the GPU memory pool, texture and view and "
     "registers the view's descriptor slot (the code the game's own bind runs before it reads the texture)."),
    ("ui_tex_release_handle", 0x3540B10, "Called",
     "The game's file-resource release `(service, u32 handle)`: drops one reference. Pairs with the lookup's reference."),
    ("ui_tex_bind", 0x379E9C0, "Called",
     "The game's picture-pane TexMap override `(pane, descriptor, index)`: the one pkg5 decoded: it keeps the previous TexMap pointer for the index."),
    ("ui_tex_clear", 0x379E470, "Called",
     "The game's picture-pane override reset `(pane)`: restores the saved TexMap pointers of both indices, drops the pane's cached shared "
     "texture and clears its pending flag. The undo of `ui_tex_bind`."),
    ("ui_tex_release_weak", 0x39C2670, "Called",
     "The `std::__shared_weak_count::__release_weak` import stub the game's shared-pointer release ends in (after the control block's "
     "`on_zero_shared`)."),
    ("ui_tex_ready_words", 0x379E610, "Relied",
     "The game's bind-readiness test in the picture setter: `bl ui_tex_poll` then `[tex+0x18] == 0`, `[tex+0] == 0xffffff` and "
     "`[tex+0x60] == 0 || [[tex+0x60]+0x18] == 3` (the three fields the plugin's own readiness test reads)."),
    ("ui_tex_ctor", 0x37A31E0, "Relied",
     "The UI texture constructor body: the holder's vtable (`main+0x52414c0`), the 0x68-byte object with the handle at +0 and the texture-info vtable "
     "(`main+0x5182f40`) at +0x38 that is the descriptor a TexMap takes."),
]

KIND = {
    "Called": "SeamKind::Called",
    "Relied": "SeamKind::Relied",
}


def sections(elf):
    shoff, = struct.unpack_from("<Q", elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    headers = []
    for i in range(shnum):
        o = shoff + i * shentsize
        name, _type, _flags, addr, offset, size = struct.unpack_from("<IIQQQQ", elf, o)
        headers.append((name, addr, offset, size))
    strtab = headers[shstrndx][2]
    out = {}
    for name, addr, offset, size in headers:
        end = elf.index(b"\0", strtab + name)
        out[elf[strtab + name:end].decode()] = (addr, offset, size)
    return out


def window(elf, secs, off):
    addr, offset, size = secs[".text"]
    assert addr <= off and off + 64 <= addr + size, hex(off)
    at = offset + off - addr
    return elf[at:at + 64]


def main():
    elf = open(sys.argv[1], "rb").read()
    secs = sections(elf)
    out = [
        "//! Stream u4's site rows (the run-time texture helper, `runtime/ui/texture.rs`): generated by `tools/gen_sites_u4.py` from the",
        "//! owned 13.0.5 `main` (the guard bytes) and checked against it by `tests/u4_sites.rs`. Same row type and 64-byte guard rule as",
        "//! the other tables; every function the helper calls and every instruction it relies on has a row.",
        "",
        "use super::guard::{SeamKind, GUARD_BYTES};",
        "use super::sites::{Feature, Site};",
        "",
    ]
    for name, off, kind, note in ROWS:
        out.append(f"pub const {name.upper()}_OFFSET: usize = {off:#x};")
    out.append("/// The lookup's `adrp`/`ldr` pair that names the file-resource service slot (inside the lookup row's window).")
    out.append("pub const UI_TEX_SERVICE_SLOT_WORDS_OFFSET: usize = 0x353da58;")
    out.append("")
    out.append(f"pub static SITES: [Site; {len(ROWS)}] = [")
    for name, off, kind, note in ROWS:
        data = window(elf, secs, off)
        out.append("    Site {")
        out.append(f'        name: "{name}",')
        out.append("        feature: Feature::Ui,")
        out.append(f"        offset: {off:#x},")
        out.append(f"        kind: {KIND[kind]},")
        out.append("        guard: [")
        for i in range(0, 64, 16):
            out.append("            " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("        ],")
        out.append(f'        note: "{note}",')
        out.append("    },")
    out.append("];")
    out.append("")
    out.append("const _: () = assert!(GUARD_BYTES == 64);")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


main()
