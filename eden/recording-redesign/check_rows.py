"""Contract for card 10a (primary, 2026-11-07): rows.json for the rc.5 grouped Eden session is complete and valid.

Run from the repository root: /usr/bin/python3 -I eden/recording-redesign/check_rows.py
Exit 0 only when every check passes. Prints one line per failure. Do not edit this file (it is the card's contract).
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path('eden/recording-redesign')
ROWS = HERE / 'rows.json'
EXPECTED = HERE / 'expected-rows.txt'
README = HERE / 'README.md'
RUNNER = Path('/home/intpa/ssbu-mod-playbook/tools/eden-runner/runner.py')
STEP_KINDS = {'play', 'gate', 'shot', 'mark', 'copy', 'json_diff', 'wait_ms', 'run', 'ui', 'call'}
HOSTS = {'surface', 'yoga', 'ally', 'xps'}


def expected_rows():
    rows = {}
    for line in EXPECTED.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        parts = line.split('\t')
        rows[parts[0].strip()] = parts[2].strip() if len(parts) > 2 else None
    return rows


def main():
    failures = []
    if not ROWS.is_file():
        print(f'FAIL {ROWS} does not exist')
        return 1
    try:
        plan = json.loads(ROWS.read_text(encoding='utf-8'))
    except json.JSONDecodeError as error:
        print(f'FAIL {ROWS} is not valid JSON: {error}')
        return 1
    if plan.get('game_id') != '01006A800016E000':
        failures.append('game_id must be 01006A800016E000')
    # Playbook MACROS.md: a segment is recorded on its first play from its recipe (or comes from the shared library);
    # nobody writes a .edenmacro.json by hand, because made-up timings aren't evidence of anything.
    for name, seg in (plan.get('segments') or {}).items():
        if isinstance(seg, dict) and 'library' in seg:
            continue
        if not isinstance(seg, dict) or not seg.get('recipe'):
            failures.append(f'segment {name}: needs a "recipe" (it is recorded on its first play)')
            continue
        if seg.get('sha256'):
            failures.append(f'segment {name}: no sha256 before it has been recorded')
        seg_file = seg.get('file')
        if seg_file and (HERE / seg_file).exists():
            failures.append(f'segment {name}: {seg_file} exists; segments are recorded from their recipe, not written by hand')
    rows = plan.get('rows') or []
    ids = [row.get('id') for row in rows]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        failures.append(f'duplicate row ids: {duplicates}')
    by_id = {row.get('id'): row for row in rows}
    expected = expected_rows()
    for row_id, media in expected.items():
        row = by_id.get(row_id)
        if row is None:
            failures.append(f'missing row {row_id}')
            continue
        steps = row.get('steps') or []
        if not steps:
            failures.append(f'row {row_id}: no steps')
        for step in steps:
            kinds = set(step) & STEP_KINDS
            if len(kinds) != 1:
                failures.append(f'row {row_id}: step {step} must have exactly one of {sorted(STEP_KINDS)}')
        if not row.get('evidence'):
            failures.append(f'row {row_id}: no evidence list')
        if not row.get('source'):
            failures.append(f'row {row_id}: no "source" naming the report section it comes from')
        if row.get('host') not in HOSTS:
            failures.append(f'row {row_id}: "host" must be one of {sorted(HOSTS)}')
        if not row.get('expect'):
            failures.append(f'row {row_id}: no "expect" (the observable result that passes it)')
        if media:
            if not any(media in str(item) for item in row.get('evidence') or []):
                failures.append(f'row {row_id}: evidence must name {media}')
            if (row.get('media') or {}).get('gif') != media:
                failures.append(f'row {row_id}: "media": {{"gif": "{media}", ...}} required')
        if row_id.startswith('adv-') and 'published' not in json.dumps(row).lower():
            failures.append(f'row {row_id}: must cite the published frame-data source it compares with')
    timed = [r for r in rows if r.get('timed') and r.get('host') == 'xps']
    if timed:
        failures.append(f'timed rows must not run on the XPS: {[r["id"] for r in timed]}')
    if not README.is_file():
        failures.append(f'{README} does not exist')
    else:
        text = README.read_text(encoding='utf-8')
        for row_id in expected:
            if row_id not in text:
                failures.append(f'README.md does not describe {row_id}')
    with tempfile.TemporaryDirectory() as out:
        dry = subprocess.run(['/usr/bin/python3', '-I', str(RUNNER), 'dry-run', str(ROWS), '--out', out],
                             capture_output=True, text=True)
        if dry.returncode != 0:
            failures.append('runner dry-run failed: ' + (dry.stdout + dry.stderr)[-1500:])
    for failure in failures:
        print('FAIL', failure)
    print(f'{len(expected)} expected rows, {len(rows)} rows in rows.json, {len(failures)} failure(s)')
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
